"""Things to do with an account, above the raw TL calls.

Plain functions taking an invoker, one module per part of the API they touch.
They do the protocol work: resolve the peer, build the request, page through
whatever comes back in slices, and hand over what the server said. What they do
not do is wrap anything in a friendly type, because that needs a client and
these deliberately do not have one.

The client above turns each of these into a method and wraps the answer. A
program that would rather not hold a client can call them with an invoker,
which is the same thing the client is doing.
"""

